# ------------------------------------------------------------------ driver
def build(report):
    out = {}
    report['plain'] = {}
    cat, catalog_icons = load_catalog()
    entries = item_outputs(out, catalog_icons, report)
    # the capsule sentinel first, then catalog order
    catalog_icons_sorted = [dict(key='_capsule')] + catalog_icons
    decor = decor_outputs(out, report)
    pictos = picto_outputs(out, report)
    glyphs = glyph_outputs(out, report)
    tiles, washi = pattern_outputs(out, report)
    arts = basket_outputs(out, report)
    lres = launcher_outputs(out, report)
    out[os.path.join(GEN, 'StickerManifest.kt')] = sticker_manifest(entries, catalog_icons_sorted)
    out[os.path.join(GEN, 'BasketManifest.kt')] = basket_manifest(arts)
    out[os.path.join(GEN, 'DecorManifest.kt')] = decor_manifest(decor, pictos, glyphs, lres)
    out[os.path.join(GEN, 'LcdGlyphs.kt')] = lcd_glyphs()
    out[os.path.join(GEN, 'PatternTiles.kt')] = pattern_tiles(tiles, washi)
    report['entries'] = entries
    report['catalog'] = catalog_icons
    report['out'] = out
    return out


def existing_generated():
    files = {}
    d = os.path.join(ROOT, DRAWABLE)
    if os.path.isdir(d):
        for f in os.listdir(d):
            if GENERATED.match(f):
                files[os.path.join(DRAWABLE, f)] = None
    g = os.path.join(ROOT, GEN)
    for f in KOTLIN_FILES:
        if os.path.exists(os.path.join(g, f)):
            files[os.path.join(GEN, f)] = None
    return files


NUM_RE = re.compile(r'(-?\d*\.?\d+(?:[eE]-?\d+)?)')


def same(a, b, tol=.0201):
    """equal except for numbers that differ by one rounding step (libm and GEOS can differ in the last ulp across
    machines; a real art change moves far more than that)."""
    if a == b:
        return True
    ta, tb = NUM_RE.split(a), NUM_RE.split(b)
    if len(ta) != len(tb):
        return False
    for i, (x, y) in enumerate(zip(ta, tb)):
        if i % 2 == 0:
            if x != y:
                return False
        elif x != y and abs(float(x) - float(y)) > tol:
            return False
    return True


def main(argv):
    check = '--check' in argv
    report = {}
    out = build(report)
    errors, warnings, measures = validate.run(report)
    if '--report' in argv:
        for line in measures:
            print('  ' + line)
    for w in warnings:
        print('warning: ' + w)
    for e in errors:
        print('error: ' + e)
    old = existing_generated()
    drift = []
    for path, content in sorted(out.items()):
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            drift.append(f'missing {path}')
            if not check:
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(content)
            continue
        with open(full, encoding='utf-8') as f:
            cur = f.read()
        if not same(cur, content):
            drift.append(f'changed {path}')
            if not check:
                with open(full, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(content)
    for path in sorted(set(old) - set(out)):
        drift.append(f'stale {path}')
        if not check:
            os.remove(os.path.join(ROOT, path))
    n_draw = sum(1 for p in out if p.endswith('.xml'))
    kinds = {}
    for p in out:
        m = re.match(r'sk_([a-z])_', os.path.basename(p))
        if m:
            kinds[m.group(1)] = kinds.get(m.group(1), 0) + 1
    summary = ', '.join(f'{v} sk_{k}_' for k, v in sorted(kinds.items()))
    size = sum(len(v.encode()) for p, v in out.items() if p.endswith('.xml'))
    print(f'stickers: {n_draw} drawables ({summary}; {size // 1024} KB of XML), {len(KOTLIN_FILES)} Kotlin manifests; '
          f'{len(report["entries"])} keys with art, {len(errors)} errors, {len(warnings)} warnings')
    if check:
        for d in drift[:40]:
            print('drift: ' + d)
        if drift:
            print(f'{len(drift)} generated files differ from the DSL: run python3 design/stickers/build_android.py')
        return 1 if (drift or errors) else 0
    if drift:
        print(f'wrote {len([d for d in drift if not d.startswith("stale")])} files, removed {len([d for d in drift if d.startswith("stale")])}')
    else:
        print('up to date')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))

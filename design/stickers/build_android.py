def load_catalog():
    with open(os.path.join(ROOT, CATALOG_JSON), encoding='utf-8') as f:
        cat = json.load(f)
    icons = list(cat['icons'])
    have = {i['key'] for i in icons}
    for k, extra in catalog_map.CATALOG_ADDITIONS.items():
        if k not in have:
            icons.append(dict(key=k, aliases=[], **extra))
    return cat, icons


def res_name(key):
    return key.lstrip('_')


# ------------------------------------------------------------------ item stickers
def item_outputs(out, catalog_icons, report):
    by_key = {i['key']: i for i in catalog_icons}
    entries = []
    stickers = []
    drawn = {}
    for icon in ICONS:
        key = catalog_map.catalog_key(icon.key, by_key)
        if key is None:
            if icon.key not in catalog_map.ORPHANS:
                raise SystemExit(f'DSL sticker {icon.key!r} has no catalog key and is not a listed orphan (catalog_map.py)')
            continue
        if key != '_capsule' and key not in by_key:
            raise SystemExit(f'catalog_map: {icon.key} -> {key!r} is not a catalog key')
        if key in drawn:
            raise SystemExit(f'two DSL stickers draw {key!r}: {drawn[key]} and {icon.key}')
        drawn[key] = icon.key
        groups, dom, sil = E.icon_layers(icon, STICKER_BASE)
        name = 'sk_i_' + res_name(key)
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml(groups, 52, 52, comment=HEADER_XML.format(src=f'sticker {icon.key!r}'))
        face_res = None
        if icon.key in FACES:
            cx, cy, fam, sp = FACES[icon.key]
            fparts = face(cx, cy, fam, sp, .9)
            face_res = 'sk_f_' + res_name(key)
            fnodes = [E.Grp('face', children=E.art_prims(fparts, STICKER_BASE))]
            out[os.path.join(DRAWABLE, face_res + '.xml')] = E.vector_xml(fnodes, 52, 52, comment=HEADER_XML.format(src=f'face of {icon.key!r}'))
            report['plain'][face_res] = (fnodes, 'item')
        cat = by_key.get(key, {})
        entries.append(dict(key=key, dsl=icon.key, res=name, face=face_res,
                            families=E.families(icon.parts, STICKER_BASE),
                            personality=catalog_map.personality(key, cat.get('category'), cat.get('personality')),
                            groups=[g.name for g in groups]))
        stickers.append((icon, key, groups, dom, sil))
    report['stickers'] = stickers
    return entries


def decor_outputs(out, report):
    names = {}
    decor = []
    for icon in DECO:
        groups, dom, sil = E.icon_layers(icon, STICKER_BASE)
        name = 'sk_d_' + icon.key
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml(groups, 52, 52, comment=HEADER_XML.format(src=f'decor {icon.key!r}'))
        names[icon.key] = name
        decor.append((icon, icon.key, groups, dom, sil))
    report['decor'] = decor
    return names


def picto_outputs(out, report):
    names = {}
    for k, v in PICTO.items():
        prims = E.flatten_svg(f'<g fill="currentColor">{v}</g>', current=engine.BP,
                              names={engine.BP: 'ink', E.WHITE: 'paper'})
        name = 'sk_p_' + k
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml([E.Grp('pictogram', children=prims)], 24, 24,
                                                                  comment=HEADER_XML.format(src=f'pictogram {k!r}'))
        report['plain'][name] = (prims, 'pictogram')
        names[k] = name
    return names


def glyph_outputs(out, report):
    names = {}
    for spec, k in GLYPHS.items():
        fill = 'currentColor' if k in GLYPH_FILLED else 'none'
        prims = E.flatten_svg(f'<g fill="{fill}" stroke="currentColor" stroke-width="2" stroke-linecap="round" '
                              f'stroke-linejoin="round">{TB[k]}</g>', current=engine.BP)
        name = 'sk_g_' + spec
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml([E.Grp('glyph', children=prims)], 24, 24,
                                                                  comment=HEADER_XML.format(src=f'toolbar glyph {k!r}'))
        report['plain'][name] = (prims, 'glyph')
        names[spec] = name
    return names


def pattern_outputs(out, report):
    tiles = {}
    for k, (svg, _) in PATTERNS.items():
        m = re.search(r"width='([\d.]+)' height='([\d.]+)'", svg)
        w, h = float(m.group(1)), float(m.group(2))
        inner = re.sub(r'^<svg[^>]*>|</svg>$', '', svg)
        prims = E.flatten_svg(inner.replace("'", '"'))
        name = 'sk_t_' + k
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml([E.Grp('tile', children=prims)], w, h,
                                                                  comment=HEADER_XML.format(src=f'tab pattern {k!r}'))
        report['plain'][name] = (prims, 'tile')
        tiles[k] = (name, w, h)
    washi = {}
    for k, (svg, w, h) in WASHI.items():
        inner = re.sub(r'^<svg[^>]*>|</svg>$', '', svg)
        prims = E.flatten_svg(inner.replace("'", '"'))
        name = 'sk_t_washi_' + k
        out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml([E.Grp('tile', children=prims)], w, h,
                                                                  comment=HEADER_XML.format(src=f'washi tape {k!r}'))
        report['plain'][name] = (prims, 'washi')
        washi[k] = (name, w, h)
    return tiles, washi


def basket_outputs(out, report):
    arts = []
    layers_report = []
    for b in BASKETS:
        kind = BASKET_KIND[b.key]
        allp = b.back + b.front
        cut, sil = E.cut_prim(allp, BASKET_BASE)
        deco = b.deco
        back_art = []
        for i, p in enumerate(b.back):
            body, trace = E.part_prims(p, BASKET_BASE)
            back_art.append((i, E.merge_fill_trace(body, trace)))
        if deco:
            a, z = deco
            nodes = [x for i, prims in back_art if i < a for x in prims]
            nodes.append(E.Grp('deco', children=[x for i, prims in back_art if a <= i < z for x in prims]))
            nodes += [x for i, prims in back_art if i >= z for x in prims]
        else:
            nodes = [x for _, prims in back_art for x in prims]
        layers = {
            'back': [E.Grp('cut', children=[cut]), E.Grp('art', children=nodes)],
            'front': [E.Grp('art', children=E.art_prims(b.front, BASKET_BASE)), E.Grp('gloss', children=E.gloss_prims(b.gloss, BASKET_BASE))],
        }
        lsil = {'back': sil}
        if b.lid_open:
            c, s = E.cut_prim(b.lid_open, BASKET_BASE)
            layers['lid_open'] = [E.Grp('cut', children=[c]), E.Grp('art', children=E.art_prims(b.lid_open, BASKET_BASE))]
            lsil['lid_open'] = s
        if b.lid_closed:
            c, s = E.cut_prim(b.lid_closed, BASKET_BASE)
            layers['lid_closed'] = [E.Grp('cut', children=[c]), E.Grp('art', children=E.art_prims(b.lid_closed, BASKET_BASE)),
                                    E.Grp('gloss', children=E.gloss_prims(b.lid_gloss, BASKET_BASE))]
            lsil['lid_closed'] = s
        if deco:
            a, z = deco
            layers['deco'] = [E.Grp('deco', children=E.art_prims(b.back[a:z], BASKET_BASE))]
        res = {}
        for layer, nodes_ in layers.items():
            name = f'sk_b_{kind}_{layer}'
            out[os.path.join(DRAWABLE, name + '.xml')] = E.vector_xml(nodes_, 80, 64, comment=HEADER_XML.format(src=f'basket {b.key!r}, {layer}'))
            res[layer] = name
        arts.append(dict(kind=kind, dsl=b.key, label=b.label, aisle=b.aisle, res=res, show_open=b.show_open,
                         rim=b.rim, hk=b.hk))
        layers_report.append((b, kind, layers, lsil))
    report['baskets'] = layers_report
    return arts


def launcher_outputs(out, report):
    s = launcher.CANVAS
    bg = '<rect width="108" height="108" fill="%s"/>' % launcher.BINDER + ''.join(
        f'<rect x="{x}" width="2" height="108" fill="{launcher.STRIPE}"/>' for x in range(0, 108, 10))
    out[os.path.join(DRAWABLE, 'sk_l_launcher_background.xml')] = E.vector_xml(
        [E.Grp('ground', children=E.flatten_svg(bg))], s, s, comment=HEADER_XML.format(src='launcher ground'))
    fg = []
    hx, hy, hs = launcher.HAMPER_BOX
    sx, sy, ss = launcher.STAR_BOX
    hamper, star = launcher.hamper(), launcher.star4holo()
    mono_parts = []
    for icon, (x, y, size) in ((hamper, (hx, hy, hs)), (star, (sx, sy, ss))):
        k = size / 52
        base = E.Matrix(k, 0, 0, k, x + 2 * k, y + 2 * k)          # the symbol's 52-unit box onto the canvas
        groups, dom, sil = E.icon_layers(icon, base)
        from shapely import affinity
        shadow = E.Prim(E.geom_d(affinity.translate(sil, 1.6 * k, 2.2 * k)), fill=engine.SHADOW, stroke=engine.SHADOW,
                        width=E.CUT_W * k, evenodd=True)
        fg.append(E.Grp(f'{icon.key}_shadow', children=[shadow]))
        fg += [E.Grp(f'{icon.key}_{g.name}', clip=g.clip, children=g.children) for g in groups if g.name != 'dominant']
        mono_parts.append(E.mono_geom(launcher.mono_icon(icon), base))     # WP2: the simplified hamper + the star
    out[os.path.join(DRAWABLE, 'sk_l_launcher_foreground.xml')] = E.vector_xml(fg, s, s, comment=HEADER_XML.format(src='launcher hamper + holo star'))
    report['plain']['sk_l_launcher_foreground'] = (fg, 'launcher')
    from shapely.ops import unary_union
    mono = E.Prim(E.geom_d(unary_union(mono_parts)), fill=engine.BP, evenodd=True)
    report['plain']['sk_l_launcher_monochrome'] = ([mono], 'launcher')
    out[os.path.join(DRAWABLE, 'sk_l_launcher_monochrome.xml')] = E.vector_xml(
        [E.Grp('mono', children=[mono])], s, s, comment=HEADER_XML.format(src='launcher hamper + star, mono'))
    return {'background': 'sk_l_launcher_background', 'foreground': 'sk_l_launcher_foreground',
            'monochrome': 'sk_l_launcher_monochrome'}



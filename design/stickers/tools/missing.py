#!/usr/bin/env python3
"""Writes design/stickers/MISSING.md: every catalog key with no DSL sticker yet, in four authoring batches.

    python3 design/stickers/tools/missing.py

Rerun it when a batch lands (keys with art drop out). The batches are balanced by count (about 30 each) and keep
related keys together so one author can reuse parts; every batch draws its category generics first (priority 1).
"""
import collections
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import build_android as B  # noqa: E402
import catalog_map as M  # noqa: E402
from icons import ICONS  # noqa: E402

# batch -> (title, rule); a key goes to the first batch whose rule claims it
BATCHES = [
    ('Batch 1 · the generics and the produce aisle',
     'the 19 remaining `*_generic` keys (priority 1: they show for every approximate item), all fruit, and the round, '
     'long and orange vegetables',
     lambda k, c: k.endswith('_generic') or c == 'fruit' or k in {'cauliflower', 'cabbage', 'zucchini', 'squash', 'pumpkin', 'chili_pepper'}),
    ('Batch 2 · fresh counters: greens and herbs, dairy, plant-based, meat, seafood, deli, bakery',
     'the leafy, stemmed and herb vegetables, then the chilled and counter aisles (breakfast has no gaps)',
     lambda k, c: c in {'vegetables', 'dairy', 'plant_based', 'meat', 'seafood', 'deli', 'bakery', 'breakfast'}),
    ('Batch 3 · centre aisles: pantry, baking, condiments, snacks, frozen',
     'shelf-stable packaging (cans, jars, bottles, boxes, bags) and the freezer',
     lambda k, c: c in {'pantry', 'baking', 'condiments', 'snacks', 'frozen'}),
    ('Batch 4 · household, health, baby, pet, garden and flowers, picnic extras and drinks',
     'non-food aisles, the florist and picnic supplies, and the drinks (the picnic cooler set)',
     lambda k, c: True),
]


def main():
    cat, icons = B.load_catalog()
    keys = {i['key'] for i in icons}
    drawn = {M.catalog_key(i.key, keys) for i in ICONS} - {None}
    missing = [i for i in icons if i['key'] not in drawn]
    order = {c['key']: n for n, c in enumerate(cat['categories'])}
    labels = {c['key']: c['label'] for c in cat['categories']}
    batches = collections.OrderedDict((b[0], []) for b in BATCHES)
    for i in sorted(missing, key=lambda i: (not i['key'].endswith('_generic'), order.get(i['category'], 99))):
        for title, _, rule in BATCHES:
            if rule(i['key'], i['category']):
                batches[title].append(i)
                break
    have = len(drawn & keys)
    out = ['# Stickers still to author',
           '',
           f'Generated by `python3 design/stickers/tools/missing.py` from `core/src/main/resources/icon_catalog.json` '
           f'(plus `peameal_bacon`, §19.1) and the DSL. **{len(icons)} catalog keys, {have} drawn, {len(missing)} to author** '
           f'(docs/DESIGN_STICKER.md §18.3 step 4, milestones M2 and M3). Until a key lands it shows the gashapon capsule.',
           '',
           '## How to author a key',
           '',
           '- Draw it in the DSL in the batch\'s own file (`design/stickers/icons_batch1.py` ... `icons_batch4.py`, loaded by '
           '`icons.py` after the r9 files), with `add(\'<catalog key>\', \'<label>\', [parts], qty=..., aisle=...)`. A sticker whose DSL '
           'key is its catalog key needs no entry in `catalog_map.py`. Never hand-place gloss: `gloss.autogloss` draws it.',
           '- Follow §3.1: 52-unit box, art in 6–42 with the base on y 42, colour-trace outlines (2u), at most two families '
           'plus white and lemon pastel, the puffy bottom band, no text, no brands. The drawHint below is what the live pipeline '
           'would have drawn; match its subject, not its colours.',
           '- Run `python3 design/stickers/build_android.py` (emits `sk_i_<key>.xml` and the manifests, runs the validators: '
           'a new key gets no grandfathering), then `python3 design/stickers/tools/roundtrip.py <key>` and review the contact '
           'sheet at 52 / 30 / 22 dp on the Day, Glow and Dusk binders before merge (§18.3 step 4, §20 item 34).',
           '- Re-use the r9 donors: `pretzel` (an orphan, kept in the DSL) for `snacks_generic`; `kibble` (dropped as a '
           'duplicate of cat food) can seed `dog_food` with a dog on the bag.',
           '']
    for (title, rule, _), (_, items) in zip(BATCHES, batches.items()):
        out += [f'## {title} ({len(items)})', '', f'_{rule[0].upper() + rule[1:]}._', '',
                '| Key | Label | Category | drawHint |', '|---|---|---|---|']
        for i in items:
            hint = i.get('drawHint', '').replace('|', '\\|')
            out.append(f'| `{i["key"]}` | {i["label"]} | {labels.get(i["category"], i["category"])} | {hint} |')
        out.append('')
    out += ['## Not item art, still to draw (WP2)',
            '',
            '- **Toolbar glyphs** (§3.4) not in the DSL yet: ' + ', '.join(f'`{g}`' for g in B.GLYPHS_SPEC if g not in B.GLYPHS) + '.',
            '- **Stamp pictogram** `capsule` (the "Everything else" stamp, §4.13).',
            '- **LCD glyphs** (§13.1) missing from `deco.G57`: `#`, `%`, `&`, `\'`, `(`, `)`, `,`, `·`, and the vector extras ★, '
            'the full moon and ♡ (♪ is in the table).',
            '- **Washi tapes** (§2.12) live as mockup CSS tiles (`design/mockup/common.py` TAPES); WP4 draws them in code or '
            'they move into the DSL as tiles.',
            '',
            '## DSL stickers with no catalog key',
            '']
    out += [f'- `{k}`: {why}' for k, why in M.ORPHANS.items()]
    out.append('')
    path = os.path.join(os.path.dirname(HERE), 'MISSING.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print(f'{len(missing)} keys to author:', ', '.join(f'{t.split(" ·")[0]} {len(v)}' for t, v in batches.items()))


if __name__ == '__main__':
    main()
